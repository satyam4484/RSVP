CREATE TABLE expenses (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    event_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NULL,
    amount DECIMAL(19, 4) NOT NULL,
    currency CHAR(3) NOT NULL,
    category VARCHAR(32) NOT NULL,
    paid_by_contact_id BIGINT NULL,
    vendor_contact_id BIGINT NULL,
    payment_status VARCHAR(32) NOT NULL,
    expense_date DATE NOT NULL,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_expenses_uuid (uuid),
    CONSTRAINT fk_expenses_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_expenses_paid_by FOREIGN KEY (paid_by_contact_id) REFERENCES contacts (id),
    CONSTRAINT fk_expenses_vendor FOREIGN KEY (vendor_contact_id) REFERENCES contacts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
