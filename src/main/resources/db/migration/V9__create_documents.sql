CREATE TABLE documents (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    owner_user_id BIGINT NOT NULL,
    event_id BIGINT NULL,
    travel_id BIGINT NULL,
    expense_id BIGINT NULL,
    contact_id BIGINT NULL,
    task_id BIGINT NULL,
    name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(150) NULL,
    size BIGINT NULL,
    storage_provider VARCHAR(32) NOT NULL,
    external_file_id VARCHAR(500) NULL,
    external_url VARCHAR(1000) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_documents_uuid (uuid),
    CONSTRAINT fk_documents_owner FOREIGN KEY (owner_user_id) REFERENCES users (id),
    CONSTRAINT fk_documents_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_documents_travel FOREIGN KEY (travel_id) REFERENCES travel (id),
    CONSTRAINT fk_documents_expense FOREIGN KEY (expense_id) REFERENCES expenses (id),
    CONSTRAINT fk_documents_contact FOREIGN KEY (contact_id) REFERENCES contacts (id),
    CONSTRAINT fk_documents_task FOREIGN KEY (task_id) REFERENCES tasks (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
