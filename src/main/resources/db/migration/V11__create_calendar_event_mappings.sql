CREATE TABLE calendar_event_mappings (
    id BIGINT NOT NULL AUTO_INCREMENT,
    calendar_connection_id BIGINT NOT NULL,
    subject_type VARCHAR(32) NOT NULL,
    subject_id BIGINT NOT NULL,
    event_id BIGINT NULL,
    travel_id BIGINT NULL,
    task_id BIGINT NULL,
    idempotency_key VARCHAR(120) NOT NULL,
    external_event_id VARCHAR(255) NULL,
    external_event_url VARCHAR(1000) NULL,
    sync_status VARCHAR(32) NOT NULL,
    sync_error VARCHAR(500) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    last_synced_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_calendar_mapping_subject (calendar_connection_id, subject_type, subject_id),
    CONSTRAINT fk_calendar_mappings_connection FOREIGN KEY (calendar_connection_id) REFERENCES calendar_connections (id),
    CONSTRAINT fk_calendar_mappings_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_calendar_mappings_travel FOREIGN KEY (travel_id) REFERENCES travel (id),
    CONSTRAINT fk_calendar_mappings_task FOREIGN KEY (task_id) REFERENCES tasks (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
