CREATE TABLE travel (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    event_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    title VARCHAR(200) NOT NULL,
    from_location VARCHAR(255) NULL,
    to_location VARCHAR(255) NULL,
    departure_at DATETIME(6) NULL,
    arrival_at DATETIME(6) NULL,
    timezone VARCHAR(64) NOT NULL,
    booking_reference VARCHAR(100) NULL,
    provider_name VARCHAR(200) NULL,
    notes TEXT NULL,
    details_json LONGTEXT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_travel_uuid (uuid),
    CONSTRAINT fk_travel_event FOREIGN KEY (event_id) REFERENCES events (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
