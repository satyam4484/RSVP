CREATE TABLE tasks (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    event_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NULL,
    status VARCHAR(32) NOT NULL,
    priority VARCHAR(32) NOT NULL,
    due_at DATETIME(6) NULL,
    completed_at DATETIME(6) NULL,
    assigned_to_user_id BIGINT NULL,
    contact_id BIGINT NULL,
    reminder_enabled TINYINT(1) NOT NULL DEFAULT 0,
    reminder_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_tasks_uuid (uuid),
    CONSTRAINT fk_tasks_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (assigned_to_user_id) REFERENCES users (id),
    CONSTRAINT fk_tasks_contact FOREIGN KEY (contact_id) REFERENCES contacts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
