package com.rsvp.common.exception;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
	VALIDATION_ERROR(HttpStatus.BAD_REQUEST),
	UNAUTHORIZED(HttpStatus.UNAUTHORIZED),
	FORBIDDEN(HttpStatus.FORBIDDEN),
	RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
	USER_NOT_FOUND(HttpStatus.NOT_FOUND),
	EVENT_NOT_FOUND(HttpStatus.NOT_FOUND),
	CONTACT_NOT_FOUND(HttpStatus.NOT_FOUND),
	TRAVEL_NOT_FOUND(HttpStatus.NOT_FOUND),
	TASK_NOT_FOUND(HttpStatus.NOT_FOUND),
	EXPENSE_NOT_FOUND(HttpStatus.NOT_FOUND),
	PAYMENT_NOT_FOUND(HttpStatus.NOT_FOUND),
	DOCUMENT_NOT_FOUND(HttpStatus.NOT_FOUND),
	PARTICIPANT_NOT_FOUND(HttpStatus.NOT_FOUND),
	NOTIFICATION_NOT_FOUND(HttpStatus.NOT_FOUND),
	CALENDAR_NOT_FOUND(HttpStatus.NOT_FOUND),
	DUPLICATE_EMAIL(HttpStatus.CONFLICT),
	DUPLICATE_CONTACT(HttpStatus.CONFLICT),
	DUPLICATE_ASSOCIATION(HttpStatus.CONFLICT),
	INVALID_STATUS_TRANSITION(HttpStatus.CONFLICT),
	INVALID_DATE_RANGE(HttpStatus.BAD_REQUEST),
	INVALID_PHONE(HttpStatus.BAD_REQUEST),
	INVALID_TIMEZONE(HttpStatus.BAD_REQUEST),
	INVALID_COORDINATES(HttpStatus.BAD_REQUEST),
	INVALID_TOKEN(HttpStatus.UNAUTHORIZED),
	ACCOUNT_INACTIVE(HttpStatus.FORBIDDEN),
	PAYMENT_EXCEEDS_BALANCE(HttpStatus.CONFLICT),
	CURRENCY_MISMATCH(HttpStatus.BAD_REQUEST),
	EXPENSE_CANCELLED(HttpStatus.CONFLICT),
	INTEGRATION_NOT_CONFIGURED(HttpStatus.SERVICE_UNAVAILABLE),
	INTEGRATION_FAILED(HttpStatus.BAD_GATEWAY),
	CALENDAR_SYNC_FAILED(HttpStatus.BAD_GATEWAY),
	FILE_STORAGE_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
	CHANNEL_NOT_ENABLED(HttpStatus.BAD_REQUEST),
	INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

	private final HttpStatus status;

	ErrorCode(HttpStatus status) {
		this.status = status;
	}

	public HttpStatus status() {
		return status;
	}
}
